namespace Plugin.ThemeKit;

public enum Theme
{
	/// <summary>
	/// Represents the system theme, which can be either light or dark depending on the user's system settings.
	/// </summary>
	System = 0,

	/// <summary>
	/// Represents the light theme, which is typically characterized by a light background and dark text.
	/// </summary>
	Light = 1,

	/// <summary>
	/// Represents the dark theme, which is typically characterized by a dark background and light text.
	/// </summary>
	Dark = 2
}
